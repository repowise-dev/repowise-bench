"""Render the cross-arm coverage tables from one or more corpus result files.

Tables on the published pages are generated by this, never typed. A hand-typed
table drifts from its result file the first time a run is repeated, and the
drift is invisible: both the table and the JSON look fine on their own.

Takes several result files because a corpus sweep is often run in parts -- a
scouting pass over one repository per language, then the remainder -- and the
published view is the union. Later files win on a repeated repository.

Scores the pairwise shared denominator only. An own-denominator rate is not a
comparison: two arms disagree about which files can carry an edge at all, so
they are answering the same question about different populations. See
`experiments/run_corpus.py::_pairwise_shared_coverage`.
"""

from __future__ import annotations

import argparse
import collections
import json
from pathlib import Path

DIRECTIONS = ("incoming", "outgoing", "either")
SETS = ("calls_only", "any_dependency")


def load(paths: list[str]) -> dict[str, dict]:
    rows: dict[str, dict] = {}
    for p in paths:
        d = json.loads(Path(p).read_text(encoding="utf-8"))
        rows.update(d["repos"])
    return rows


def cell(row: dict, a: str, b: str) -> dict | None:
    pw = row.get("shared", {}).get("pairwise", {})
    return pw.get(f"{a}__vs__{b}") or pw.get(f"{b}__vs__{a}")


def verdict(x: dict, y: dict) -> str:
    """`tie` whenever the Wilson intervals overlap.

    A point-estimate gap inside two overlapping intervals is not a win, and
    this benchmark reports it as a tie no matter which side it favours.
    """
    if not (x["ci_high"] < y["ci_low"] or y["ci_high"] < x["ci_low"]):
        return "tie"
    return "A" if x["rate"] > y["rate"] else "B"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("results", nargs="+", help="result.json paths; later wins")
    ap.add_argument("--a", default="repowise")
    ap.add_argument("--b", default="codebase-memory-mcp")
    ap.add_argument("--set", dest="edge_set", default="calls_only", choices=SETS)
    ap.add_argument("--direction", default="incoming", choices=DIRECTIONS)
    args = ap.parse_args()

    key = f"{args.edge_set}__{args.direction}"
    rows = load(args.results)
    by_lang: dict[str, list] = collections.defaultdict(list)
    for name, row in rows.items():
        by_lang[row["language"]].append((name, row))

    print(f"# {args.a} vs {args.b} - {args.edge_set}, {args.direction}")
    print(f"# {len(rows)} repositories, pairwise shared denominator\n")
    print(f"| language | repos | denominator | {args.a} | {args.b} | separated |")
    print("|---|---:|---:|---:|---:|---|")

    tally: collections.Counter = collections.Counter()
    for lang in sorted(by_lang):
        cells = by_lang[lang]
        denom = a_hit = b_hit = 0
        verds = []
        for name, row in cells:
            c = cell(row, args.a, args.b)
            if not c or not c.get("denominator"):
                continue
            n = c["denominator"]
            x, y = c[args.a][key], c[args.b][key]
            denom += n
            a_hit += x["covered"]
            b_hit += y["covered"]
            v = verdict(x, y)
            tally[v] += 1
            if v != "tie":
                verds.append(f"{name}")
        if not denom:
            continue
        sep = ", ".join(verds) if verds else "none - all ties"
        print(f"| {lang} | {len(cells)} | {denom} | {a_hit / denom:.3f} "
              f"| {b_hit / denom:.3f} | {sep} |")

    n_a, n_b, n_t = tally["A"], tally["B"], tally["tie"]
    print(f"\n# per-repository verdicts: {args.a} {n_a}, {args.b} {n_b}, ties {n_t}")
    print("# A pooled per-language rate is a weighted mean over repositories, not")
    print("# a sample of software. Read the per-repository verdicts beside it.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
