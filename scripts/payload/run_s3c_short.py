"""Session C, step 1: six SHORT (3-task) bare sessions on the EXISTING cell.

`RESULT_S3.md` section 4.3 recommends many short sessions over few long ones, on
the grounds that the 31.9% CV is generated by within-session compounding and a
3-task session has less session left to tax. That is a prediction, and it is
cheap to test on ground we already have baselines for. Going straight to a big
repo would change session length AND repo size at once, and nothing would be
attributable.

Pre-registration, thresholds and anti-fake-win controls, all fixed before this
file was written and before any cost data was read:
`local-stash/competitive-proof/session-cost-eval/06_SESSION_C_PREREG.md` section 1.

Everything is held identical to `run_s3_stage1.py` except `--limit-tasks 3`, so
task count is the only thing that varies. Same cell, same task order, same
model, same condition, no treatment.

Sequential for the same reason stage 1 was: three concurrent agent sessions
contend for CPU on this machine, and wall-clock pressure is one of the few
things that could plumb into a trajectory. That would put variance INTO the
number whose whole job is to measure variance.

Output goes to its OWN jsonl. Appending to `sessions_s3.jsonl` would put 3-task
and 11-task rows for the same cell in one file, and every later reader would
have to know which is which -- the setup for "compare totals over unequal task
counts", which is a standing trap in this workstream.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from pathlib import Path

BENCH = Path(__file__).resolve().parents[2]
PY = Path(r"C:\Users\ragha\Desktop\repowise\.venv\Scripts\python.exe")
ARMS = BENCH / "harness" / "session_arms.py"
CONFIG = BENCH / "configs" / "session_cost_eval_cellA_rich.yaml"
OUT = (BENCH / "results" / "bakeoff_2026_08" / "session-cost-eval"
       / "sessions_s3_short.jsonl")

ARM_NAMES = [f"c0-short-r{i}" for i in range(1, 7)]
CONDITION = "unenforced"   # a bare arm has no tool to be nudged toward
LIMIT_TASKS = 3            # T01 retrieval, T02 architecture, T03 edit


def _arms(arm: str, *extra: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [str(PY), str(ARMS), "--config", str(CONFIG), "--arm", arm,
         "--condition", CONDITION, *extra],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        cwd=str(BENCH), env=os.environ.copy())


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    for arm in ARM_NAMES:
        r = _arms(arm, "--prepare", "--gate", "--emit-cmd", "--out", str(OUT))
        if r.returncode != 0:
            print(f"!! {arm} FAILED ITS GATE. Stopping.\n{r.stdout[-1500:]}",
                  file=sys.stderr)
            return 1
        cmd = json.loads(r.stdout)["cmd"]

        # `emit_cmd` has no --limit-tasks knob and does not need one: it is a
        # property of THIS run, not of the arm. Appended here so the harness
        # keeps one meaning of an arm and the truncation is visible in the
        # command that is actually spawned.
        cmd += ["--limit-tasks", str(LIMIT_TASKS)]

        print(f"\n{'=' * 70}\n=== {arm}  ({time.strftime('%H:%M:%S')})  "
              f"{LIMIT_TASKS} tasks\n{'=' * 70}", flush=True)
        t0 = time.time()
        p = subprocess.run(cmd, cwd=str(BENCH), env=os.environ.copy())
        print(f"=== {arm} exited {p.returncode} after {time.time() - t0:.0f}s",
              flush=True)
        if p.returncode != 0:
            print(f"!! {arm} exited non-zero. Stopping rather than running the "
                  f"rest on top of a broken arm.", file=sys.stderr)
            return p.returncode

    print(f"\nstep 1 complete: {len(ARM_NAMES)} short bare arms -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
